/** Both arrays above, case-folded once at module load. Lower-cased for the
 * same cross-platform reason `excludeWorkspaceOwnedNames` folds case: on
 * Windows and on macOS's default filesystem, a generated `Typing/` directory
 * resolves for `import typing` exactly as a same-cased one would, so a
 * case-sensitive comparison here would let the shadow through on the two
 * platforms most of this extension's users are on. */
const CASE_FOLDED = new Set(
  [
    ...TYPESHED_STDLIB_TOP_LEVEL_NAMES,
    ...TYPESHED_THIRD_PARTY_TOP_LEVEL_NAMES,
  ].map((name) => name.toLowerCase()),
);

/**
 * Whether Pylance already resolves `topLevelName` from its own bundled
 * typeshed — in which case 10b must not generate a stub for it. See this
 * module's own doc comment for what each half costs when it is not excluded.
 */
export function resolvesFromBundledTypeshed(topLevelName: string): boolean {
  return CASE_FOLDED.has(topLevelName.toLowerCase());
}
