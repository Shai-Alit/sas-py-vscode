/**
 * Every top-level module name Pylance already resolves from its own bundled
 * typeshed — the names 10b's generated stub tree must never claim.
 *
 * **This module must never import `vscode`.** It is pure data plus one
 * predicate, consumed by `./stubGenerator.ts`'s `generateStubTree`.
 *
 * ## Why this list has to exist
 *
 * Pyright resolves an import against `stubPath` **first** — ahead of
 * workspace source, ahead of installed packages, and ahead of both halves of
 * its bundled typeshed
 * (https://github.com/microsoft/pyright/blob/main/docs/import-resolution.md,
 * checked 2026-09-16). `excludeWorkspaceOwnedNames` (`./stubGenerator.ts`)
 * and `selectPackagesToStub` (`./stubSyncPlan.ts`) already cover the first
 * two. This module covers the third, and it is the only one of the three
 * whose failure mode is silent: Finding 10.7 (`docs/phases/phase-10.md`'s
 * Probe findings) measured both halves directly against pyright 1.1.414.
 *
 * - **stdlib.** A generated `typing/__init__.pyi` took precedence over
 *   typeshed's own `typing`, and a file whose only real type error was a
 *   `reportReturnType` violation went from 1 error to **0 errors, 0
 *   warnings** — real type-checking for that module silently disabled
 *   workspace-wide, with nothing shown to say so. Backport distributions
 *   (`typing`, `dataclasses`, `contextvars`, `configparser`, and similar) do
 *   turn up in real `pip list` output, and the stdlib is not in
 *   `site-packages`, so neither of the other two exclusions ever sees them.
 * - **Bundled third-party stubs.** For a package that is genuinely remote-only,
 *   typeshed already supplies `reportMissingModuleSource` — a *warning*,
 *   which is exactly the outcome this whole feature exists to reach — and
 *   supplies real types with it. Measured on `simplejson`: without a generated
 *   stub, pyright reported the `reportMissingModuleSource` warning **and**
 *   caught a genuine `reportAssignmentType` error; with one, the identical
 *   warning remained and the error was gone. Stubbing these names therefore
 *   buys nothing and costs the real types — a strict regression.
 *
 * ## Why a static list rather than reading Pylance's own typeshed at runtime
 *
 * Enumerating `ms-python.vscode-pylance`'s bundled `typeshed-fallback/`
 * directory would never go stale, but it means a filesystem read of another
 * extension's internal layout threaded from the `vscode` shell down into this
 * pure module — a new port and a new parameter through
 * `generateStubTree`/`selectPackagesToStub`, for a list that moves a few
 * entries per typeshed release. Recorded as deferred follow-up work in
 * `docs/phases/phase-10.md` rather than taken on here.
 *
 * **Staleness fails safe in both directions.** A name typeshed has since
 * dropped only means one package goes unstubbed — the user keeps the
 * `reportMissingImports` they had before this feature existed. A name typeshed
 * has since added only means that one package keeps the pre-existing
 * `Any`-instead-of-real-types behaviour. Neither silently breaks a workspace,
 * which is the property that matters: the failure this guards against is
 * losing type-checking without being told.
 *
 * ## Provenance
 *
 * Generated from `pyright@1.1.414`'s `dist/typeshed-fallback/` on 2026-09-16 —
 * `stdlib/` for the first array, the union of every `stubs/<distribution>/`
 * for the second (201 distributions). Entries that are not legal Python
 * identifiers were dropped, since `generateStubTree` would reject them
 * anyway. To regenerate, list the top-level `.pyi` files and directories of
 * each, minus `VERSIONS`/`METADATA.toml`.
 */

